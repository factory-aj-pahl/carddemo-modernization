"""Generate docs/INVENTORY.md from the sources so it never drifts from the code."""

from __future__ import annotations

import re
from pathlib import Path

from . import procedure
from .copybook import parse_records
from .source import REPO_ROOT, Repository, SourceFile

INVENTORY_PATH = REPO_ROOT / "docs" / "INVENTORY.md"

_CALL_RE = re.compile(r"\bCALL\s+'([A-Z0-9#$@]+)'", re.IGNORECASE)
_CICS_PROGRAM_RE = re.compile(r"\b(?:LINK|XCTL)\s+PROGRAM\s*\(\s*'([A-Z0-9#$@]+)'\s*\)", re.IGNORECASE)


def _features(f: SourceFile) -> str:
    flags = [
        name for name, on in (("CICS", f.uses_cics), ("Db2", f.uses_sql), ("IMS", f.uses_dli), ("MQ", f.uses_mq)) if on
    ]
    return ", ".join(flags) or "-"


def _calls(f: SourceFile) -> str:
    text = "\n".join(line.code for line in f.code_lines)
    names = sorted(set(_CALL_RE.findall(text)) | set(_CICS_PROGRAM_RE.findall(text)))
    return ", ".join(n.upper() for n in names) or "-"


def _record_summary(book: SourceFile) -> str:
    if book.suffix != ".cpy" or "/cpy-bms/" in book.rel or "PROCEDURE" in book.upper_code:
        return "-"
    try:
        records = parse_records(book)
    except (ValueError, IndexError):
        return "-"
    parts = [f"{r.name} ({r.length})" for r in records if r.length]
    return "; ".join(parts[:3]) + (" ..." if len(parts) > 3 else "") if parts else "-"


def render(repo: Repository) -> str:
    users: dict[str, set[str]] = {}
    for f in repo.files:
        for _, name in f.copies:
            users.setdefault(name, set()).add(f.member)

    out = [
        "# CardDemo source inventory",
        "",
        "<!-- Generated by `python3 -m tools.carddemo inventory`. Do not edit by hand. -->",
        "",
        "Generated from the COBOL sources under `app/`. CI fails if this file is out of date,",
        "so regenerate it with `make docs` after adding, removing, or changing programs and copybooks.",
        "",
        "## Programs",
        "",
        "| Member | Module | Kind | Uses | Lines | Paragraphs | Max complexity | Calls | Copybooks |",
        "|:--|:--|:--|:--|--:|--:|--:|:--|:--|",
    ]
    for f in sorted(repo.programs, key=lambda f: (f.module != "base", f.module, f.member)):
        model = procedure.build(repo, f)
        paragraphs = len(model.paragraphs) if model else 0
        max_cc = max((p.complexity for p in model.ordered), default=0) if model else 0
        copies = ", ".join(sorted({name for _, name in f.copies})) or "-"
        kind = "Online (CICS)" if f.uses_cics else "Batch"
        out.append(
            f"| [{f.member}](../{f.rel}) | {f.module} | {kind} | {_features(f)} | {len(f.lines)} "
            f"| {paragraphs} | {max_cc} | {_calls(f)} | {copies} |"
        )

    out += [
        "",
        "## Copybooks",
        "",
        "Record lengths are computed from the PICTURE and USAGE clauses.",
        "",
        "| Member | Module | Records (bytes) | Used by |",
        "|:--|:--|:--|:--|",
    ]
    for name in sorted(repo.copybooks):
        for book in repo.copybooks[name]:
            used_by = ", ".join(sorted(users.get(name, set()))) or "**unused**"
            out.append(f"| [{name}](../{book.rel}) | {book.module} | {_record_summary(book)} | {used_by} |")
    return "\n".join(out) + "\n"


def write(repo: Repository, path: Path = INVENTORY_PATH) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(repo))


def is_current(repo: Repository, path: Path = INVENTORY_PATH) -> bool:
    return path.exists() and path.read_text() == render(repo)
